def solid(shape, colour):
    shape.fill.solid()
    shape.fill.fore_color.rgb = colour
    shape.line.fill.background()


def box(slide, x, y, w, h, colour=None, line=None):
    from pptx.enum.shapes import MSO_SHAPE

    s = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    if colour is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = colour
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(1)
    s.shadow.inherit = False
    return s


def text(
    slide,
    body,
    x,
    y,
    w,
    h,
    size=18,
    colour=TEXT,
    font=SANS,
    bold=False,
    spacing=0,
    align=PP_ALIGN.LEFT,
    leading=1.25,
    link=None,
    underline=False,
):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    for i, line in enumerate(body.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = leading
        r = p.add_run()
        r.text = line
        r.font.size = Pt(size)
        r.font.color.rgb = colour
        r.font.name = font
        r.font.bold = bold
        r.font.underline = underline
        if link:
            # A real hyperlink, so it is clickable in the slideshow rather than
            # a URL somebody has to type out while everyone watches.
            r.hyperlink.address = link
            # PowerPoint recolours hyperlinks to the theme's link colour unless
            # the run's own colour is reasserted after the link is set.
            r.font.color.rgb = colour
        if spacing:
            # python-pptx has no letter-spacing API; set it on the XML.
            r.font._rPr.set("spc", str(int(spacing * 100)))
    return tb


def slide(prs, eyebrow=None, eyebrow_colour=AIR):
    s = prs.slides.add_slide(prs.slide_layouts[6])  # blank
    bg = box(s, 0, 0, W, H, GROUND)
    bg.shadow.inherit = False
    if eyebrow:
        text(
            s,
            eyebrow.upper(),
            M,
            Inches(0.62),
            Inches(9),
            Inches(0.3),
            size=11,
            colour=eyebrow_colour,
            font=MONO,
            bold=True,
            spacing=2.6,
        )
    return s


def heading(s, body, y=Inches(1.12), size=34, colour=TEXT, w=Inches(11.6)):
    return text(s, body, M, y, w, Inches(1.6), size=size, colour=colour, font=MONO, bold=True, leading=1.1)


def rule(s, y, w=Inches(11.6)):
    box(s, M, y, w, Emu(9525), EDGE)


_page = [0]


def footer(s, n=None):
    """The page number counts itself.

    It used to be passed in, which made inserting a slide in the middle a
    renumbering job across the whole file — the kind of chore that ends with two
    slides both called 07 in front of an audience.
    """
    if n is None:
        _page[0] += 1
        n = _page[0]
    text(
        s,
        f"AIR DEBT  ·  {FACTS['url']}",
        M,
        H - Inches(0.62),
        Inches(7),
        Inches(0.3),
        size=9,
        colour=DIM,
        font=MONO,
        spacing=1.8,
    )
    text(
        s,
        f"{n:02d}",
        W - M - Inches(1),
        H - Inches(0.62),
        Inches(1),
        Inches(0.3),
        size=9,
        colour=DIM,
        font=MONO,
        align=PP_ALIGN.RIGHT,
    )


def fade(s, ms=450):
    """
    A short cross-fade onto this slide.

    python-pptx has no transition API, so the element is written into the slide's
    XML directly. The schema puts `p:transition` after `p:clrMapOvr` and before
    `p:timing`, and PowerPoint is strict about that order — appended anywhere else
    the file opens with a repair prompt, which is the worst possible thing to
    happen to a deck in front of somebody.

    A fade and nothing else, deliberately. Every other transition PowerPoint
    offers announces itself, and an effect the audience notices is an effect that
    took their attention off the slide. This one is only there so a slide arrives
    rather than snapping.
    """
    from pptx.oxml.ns import qn

    sld = s._element
    for existing in sld.findall(qn("p:transition")):
        sld.remove(existing)

    tr = sld.makeelement(qn("p:transition"), {"spd": "med", "advClick": "1"})
    tr.append(sld.makeelement(qn("p:fade"), {}))

    # After clrMapOvr if it is there, otherwise straight after cSld.
    anchor = sld.find(qn("p:clrMapOvr")) if sld.find(qn("p:clrMapOvr")) is not None else sld.find(qn("p:cSld"))
    anchor.addnext(tr)
    return tr


def picture(s, name, x, y, w):
    """A screenshot, with a hairline so it does not float on the dark."""
    f = SHOTS / name
    if not f.exists():
        return None
    pic = s.shapes.add_picture(str(f), x, y, width=w)
    box(s, x, y, pic.width, pic.height, None, EDGE)
    return pic


