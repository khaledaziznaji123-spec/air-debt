"""
Build the investor deck as a real PowerPoint file.

    py pitch-deck.py        ->  Air-Debt.pptx

A SCRIPT RATHER THAN A FILE, for the same reason the art is generated by scripts
rather than drawn: a deck is full of numbers that go stale — the air ceiling, the
test count, what a careful clear costs — and a .pptx is a zip nobody is going to
open and correct. This reads the real figures where it can and keeps the rest in
one block at the top, so bringing the deck up to date is running it again.

The design is the game's, deliberately: the palette is lifted from
`src/app/globals.css`, the display face is monospace because the HUD is
monospace, and the slides are dark because the game is. It is the same system as
`pitch.html`, in a format that opens on somebody else's laptop with no internet.
"""

